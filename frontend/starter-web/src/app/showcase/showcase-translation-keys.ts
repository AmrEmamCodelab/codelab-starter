type Leaves<T> = T extends string ? T : { [K in keyof T]: Leaves<T[K]> }[keyof T];

/** Every showcase translation key (the bundles must hold each one in ar and en). */
export type ShowcaseTranslationKey = Leaves<typeof ShowcaseTranslationKeys>;

function leaves(node: unknown): string[] {
  return typeof node === 'string' ? [node] : Object.values(node as object).flatMap(leaves);
}

/** {@link ShowcaseTranslationKeys} as a flat list. */
export const SHOWCASE_TRANSLATION_KEYS: readonly ShowcaseTranslationKey[] = leaves(
  ShowcaseTranslationKeys,
) as ShowcaseTranslationKey[];
