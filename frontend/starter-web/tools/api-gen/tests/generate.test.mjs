// @vitest-environment node
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';
import { afterEach, beforeEach, describe, expect, it } from 'vitest';
import { buildOutputs, parseArguments, run } from '../generate.mjs';
import { ApiGenPaths, ExitCodes } from '../lib/constants.mjs';
import { renderApiClient } from '../lib/openapi-client.mjs';
import { normaliseLineEndings, syncOutputs } from '../lib/outputs.mjs';

const FIXTURES_DIR = fileURLToPath(new URL('./fixtures', import.meta.url));
const CONTRACT_OPENAPI = path.join(FIXTURES_DIR, 'contract-openapi.v1.json');
const CONTRACT_PERMISSIONS = path.join(FIXTURES_DIR, 'contract-permissions.json');
const WIRE_ID_OPENAPI = path.join(FIXTURES_DIR, 'wire-id-openapi.json');
const FAKE_CLIENT_BODY = 'export interface paths {}\n';

/** A stand-in for openapi-typescript: records the options it was given and prints a fixed body. */
function fakeModules() {
  const calls = [];
  return {
    calls,
    modules: {
      ts,
      openapi: {
        default: async (document, options) => { calls.push({ document, options }); return []; },
        astToString: () => FAKE_CLIENT_BODY,
      },
    },
  };
}

/** openapi-typescript when it is installed (frontend devDependency), else null: the end-to-end case is skipped. */
async function realModules() {
  try {
    return { openapi: await import('openapi-typescript'), ts };
  } catch {
    return null;
  }
}
const REAL_MODULES = await realModules();

describe('parseArguments', () => {
  it('defaults to the docs/generated inputs', () => {
    expect(parseArguments([])).toEqual({
      check: false, help: false, openapi: ApiGenPaths.openapiInput, permissions: ApiGenPaths.permissionsInput,
    });
  });

  it('reads --check and the input overrides', () => {
    expect(parseArguments(['--check', '--openapi', 'a.json', '--permissions', 'b.json'])).toMatchObject({
      check: true, openapi: 'a.json', permissions: 'b.json',
    });
  });

  it.each([[['--openapi']], [['--permissions', '--check']], [['--bogus']], [['extra']]])('refuses %j', (argv) => {
    expect(parseArguments(argv).error).toBeTypeOf('string');
  });
});

describe('syncOutputs', () => {
  let dir;
  beforeEach(() => { dir = fs.mkdtempSync(path.join(os.tmpdir(), 'starter-api-gen-sync-')); });
  afterEach(() => fs.rmSync(dir, { recursive: true, force: true }));

  it('writes missing files, then reports nothing to do; CRLF on disk is not drift', () => {
    const file = path.join(dir, 'nested', 'a.ts');
    expect(syncOutputs([{ path: file, content: 'x\ny\n' }], { check: false })).toEqual({ drifted: [file], written: [file] });
    fs.writeFileSync(file, 'x\r\ny\r\n');
    expect(syncOutputs([{ path: file, content: 'x\ny\n' }], { check: true })).toEqual({ drifted: [], written: [] });
  });

  it('with check, reports drift without writing', () => {
    const file = path.join(dir, 'a.ts');
    fs.writeFileSync(file, 'old\n');
    expect(syncOutputs([{ path: file, content: 'new\n' }], { check: true })).toEqual({ drifted: [file], written: [] });
    expect(fs.readFileSync(file, 'utf8')).toBe('old\n');
  });

  it('normalises line endings', () => {
    expect(normaliseLineEndings('a\r\nb\n')).toBe('a\nb\n');
  });
});

describe('run', () => {
  let appDir;
  const logs = [];
  const errors = [];
  const sink = { log: (line) => logs.push(line), error: (line) => errors.push(line) };
  const inputs = ['--openapi', CONTRACT_OPENAPI, '--permissions', CONTRACT_PERMISSIONS];

  beforeEach(() => {
    appDir = fs.mkdtempSync(path.join(os.tmpdir(), 'starter-api-gen-run-'));
    logs.length = 0;
    errors.length = 0;
  });
  afterEach(() => fs.rmSync(appDir, { recursive: true, force: true }));

  it('writes both outputs, then --check passes', async () => {
    const { modules, calls } = fakeModules();
    expect(await run(inputs, { appDir, modules, ...sink })).toBe(ExitCodes.ok);
    const keys = fs.readFileSync(path.join(appDir, ApiGenPaths.permissionKeysOutput), 'utf8');
    expect(keys).toContain("DashboardView: 'dashboard.view'");
    const client = fs.readFileSync(path.join(appDir, ApiGenPaths.clientOutput), 'utf8');
    expect(client.startsWith('// @generated by tools/api-gen')).toBe(true);
    expect(client.endsWith(FAKE_CLIENT_BODY)).toBe(true);
    expect(calls[0].options).toMatchObject({ alphabetize: true, inject: "import type { WireId } from '@codelab/ng-security';" });
    expect(await run(['--check', ...inputs], { appDir, modules, ...sink })).toBe(ExitCodes.ok);
  });

  it('--check exits 1 and names the stale file when an output was edited', async () => {
    const { modules } = fakeModules();
    await run(inputs, { appDir, modules, ...sink });
    fs.appendFileSync(path.join(appDir, ApiGenPaths.permissionKeysOutput), '// hand edit\n');
    expect(await run(['--check', ...inputs], { appDir, modules, ...sink })).toBe(ExitCodes.failure);
    expect(errors.join('\n')).toContain(ApiGenPaths.permissionKeysOutput);
  });

  it('--check exits 1 when the outputs do not exist yet', async () => {
    expect(await run(['--check', ...inputs], { appDir, modules: fakeModules().modules, ...sink })).toBe(ExitCodes.failure);
  });

  it('exits 1 with the DocsGen hint when an input is missing', async () => {
    const code = await run(['--openapi', path.join(appDir, 'missing.json'), '--permissions', CONTRACT_PERMISSIONS], { appDir, modules: fakeModules().modules, ...sink });
    expect(code).toBe(ExitCodes.failure);
    expect(errors.join('\n')).toMatch(/Starter\.DocsGen/);
  });

  it('exits 1 when an input is not JSON', async () => {
    const broken = path.join(appDir, 'broken.json');
    fs.writeFileSync(broken, '{ nope');
    expect(await run(['--openapi', broken, '--permissions', CONTRACT_PERMISSIONS], { appDir, modules: fakeModules().modules, ...sink })).toBe(ExitCodes.failure);
    expect(errors.join('\n')).toMatch(/not valid JSON/);
  });

  it('exits 2 on a usage error and 0 on --help', async () => {
    expect(await run(['--nope'], { appDir, ...sink })).toBe(ExitCodes.usage);
    expect(await run(['--help'], { appDir, ...sink })).toBe(ExitCodes.ok);
  });
});

describe.skipIf(REAL_MODULES === null)('with openapi-typescript installed', () => {
  it('turns every PublicId of the fixture into a branded WireId', async () => {
    const document = JSON.parse(fs.readFileSync(WIRE_ID_OPENAPI, 'utf8'));
    const client = await renderApiClient(document, REAL_MODULES);
    expect(client).toMatch(/import type \{ WireId \} from ["']@codelab\/ng-security["'];/);
    expect(client).toContain("id: WireId<'record'>;");
    expect(client).toContain("requestTypeId: WireId<'request-type'>;");
    expect(client).toContain("ownerId?: WireId<'owner'> | null;");
    expect(client).toContain("attachmentIds?: WireId<'attachment'>[];");
    expect(client).toContain("approverRef?: WireId<'employee'>;");
    expect(client).toContain("recordId: WireId<'record'>;");
    expect(client).toContain('reference?: string;');
  });

  it('builds the contract client with a session-user id', async () => {
    const outputs = await buildOutputs({ appDir: FIXTURES_DIR, openapiPath: CONTRACT_OPENAPI, permissionsPath: CONTRACT_PERMISSIONS, modules: REAL_MODULES });
    expect(outputs[0].content).toContain("id: WireId<'session-user'>;");
  });
});
