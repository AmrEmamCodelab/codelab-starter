// @vitest-environment node
import { readFileSync } from 'node:fs';
import { describe, expect, it } from 'vitest';
import { permissionKeyName, readPermissionEntries, renderPermissionKeys } from '../lib/permission-keys.mjs';

const CONTRACT_PERMISSIONS = JSON.parse(readFileSync(new URL('./fixtures/contract-permissions.json', import.meta.url), 'utf8'));

describe('permissionKeyName', () => {
  it.each([
    ['dashboard.view', 'DashboardView'],
    ['access.admin.view', 'AccessAdminView'],
    ['service-requests.submit', 'ServiceRequestsSubmit'],
    ['identity.users.reset-password', 'IdentityUsersResetPassword'],
  ])('%s -> %s', (key, name) => {
    expect(permissionKeyName(key)).toBe(name);
  });

  it.each(['dashboard', 'Dashboard.view', 'dashboard..view', 'dashboard.view.', '1x.view', '', 42])('refuses %j', (key) => {
    expect(() => permissionKeyName(key)).toThrow(/Invalid permission key/);
  });
});

describe('readPermissionEntries', () => {
  it('sorts by key ordinally', () => {
    const entries = readPermissionEntries({ permissions: [{ key: 'b.view' }, { key: 'a.view' }, { key: 'a-b.view' }] });
    expect(entries.map((entry) => entry.key)).toEqual(['a-b.view', 'a.view', 'b.view']);
  });

  it('refuses a document without a permissions array', () => {
    expect(() => readPermissionEntries({})).toThrow(/"permissions" array/);
    expect(() => readPermissionEntries(null)).toThrow(/"permissions" array/);
  });

  it('refuses an entry without a key', () => {
    expect(() => readPermissionEntries({ permissions: [{ module: 'Access' }] })).toThrow(/permissions\[0\]/);
  });

  it('refuses duplicate keys', () => {
    expect(() => readPermissionEntries({ permissions: [{ key: 'a.view' }, { key: 'a.view' }] })).toThrow(/duplicate permission key/);
  });

  it('refuses two keys that map to the same constant name', () => {
    expect(() => readPermissionEntries({ permissions: [{ key: 'a.b-c' }, { key: 'a.b.c' }] })).toThrow(/duplicate constant name "ABC"/);
  });
});

describe('renderPermissionKeys', () => {
  it('renders the contract shape for the phase 2 keys', () => {
    expect(renderPermissionKeys(CONTRACT_PERMISSIONS)).toBe(
      [
        '// @generated by tools/api-gen from docs/generated/permissions.json. Do not edit: run `npm run api:gen`.',
        '',
        'export const PermissionKeys = {',
        '  /** Open the access administration area. (module Access) */',
        "  AccessAdminView: 'access.admin.view',",
        '  /** Open the dashboard. (module Access) */',
        "  DashboardView: 'dashboard.view',",
        '} as const;',
        '',
        'export type PermissionKey = typeof PermissionKeys[keyof typeof PermissionKeys];',
        '',
      ].join('\n'),
    );
  });

  it('omits the comment when an entry has no description or module, and escapes a comment terminator', () => {
    const text = renderPermissionKeys({ permissions: [{ key: 'a.view' }, { key: 'b.view', description: 'ends */ here' }] });
    expect(text).toContain("export const PermissionKeys = {\n  AView: 'a.view',\n");
    expect(text).toContain('/** ends *\\/ here */');
  });

  it('is deterministic whatever the input order', () => {
    const reversed = { permissions: [...CONTRACT_PERMISSIONS.permissions].reverse() };
    expect(renderPermissionKeys(reversed)).toBe(renderPermissionKeys(CONTRACT_PERMISSIONS));
  });
});
