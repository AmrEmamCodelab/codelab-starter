namespace Starter.Tools.DocsGate.Repository;

/// <summary>
/// Recognises the nested module CLAUDE.md files that tools/rules-engine emits. They are recompiled from
/// module.rules.yaml and rules/base.rules.yaml, so a change to one is not a module change: a change to the
/// module's own rules file still counts, because that file is listed separately.
/// </summary>
internal static class GeneratedModuleInstructions
{
    public const string FileName = "CLAUDE.md";

    /// <summary>The first line every rules-engine output starts with.</summary>
    public const string Marker = "<!-- GENERATED by tools/rules-engine";

    /// <summary>
    /// True when <paramref name="relativePath"/> is a CLAUDE.md that still exists and starts with <see cref="Marker"/>.
    /// A deleted or hand-written CLAUDE.md is not generated, so it still counts as a module change.
    /// </summary>
    public static bool IsGenerated(string root, string relativePath)
    {
        if (!string.Equals(RepositoryPaths.FileName(relativePath), FileName, StringComparison.Ordinal))
        {
            return false;
        }

        var fullPath = RepositoryPaths.ToFullPath(root, relativePath);
        if (!File.Exists(fullPath))
        {
            return false;
        }

        using var reader = new StreamReader(fullPath);
        var firstLine = reader.ReadLine();
        return firstLine is not null && firstLine.TrimStart('﻿').StartsWith(Marker, StringComparison.Ordinal);
    }
}
