# npm half of the closure (b): `npm ci --cache <kit>/npm-cache` fills the cache with every tarball (Codelab and
# third-party); `npm ci --offline --cache ./npm-cache` installs from it. Tarballs a lock file references by
# file: path (feed/npm/*.tgz) are copied into npm-files/ at their source-relative path.

# Lock files have an empty-string key (the root package) that Windows PowerShell 5.1 ConvertFrom-Json rejects, so
# they are read as dictionaries: ConvertFrom-Json -AsHashtable on PowerShell 6+, JavaScriptSerializer on 5.1.
function Read-KitJsonDictionary([string] $Path) {
    $text = Get-Content -LiteralPath $Path -Raw -Encoding UTF8
    if ($PSVersionTable.PSVersion.Major -ge $script:HashtableJsonMinVersion) { return ($text | ConvertFrom-Json -AsHashtable) }
    Add-Type -AssemblyName System.Web.Extensions
    $serializer = [Web.Script.Serialization.JavaScriptSerializer]::new()
    $serializer.MaxJsonLength = [int]::MaxValue
    return $serializer.DeserializeObject($text)
}

function Get-KitLockPackages([string] $InstallRootFull) {
    $lock = Read-KitJsonDictionary (Join-Path $InstallRootFull $script:PackageLockFile)
    if (-not $lock.ContainsKey($script:NpmLockPackagesKey)) { return @{} }
    return $lock[$script:NpmLockPackagesKey]
}

# Source-relative paths of the .tgz files the install root's lock file installs by file: path.
function Get-KitNpmFileTarballs([string] $InstallRootFull, [string] $SourceRoot) {
    $packages = Get-KitLockPackages $InstallRootFull
    $found = @()
    foreach ($value in $packages.Values) {
        if (-not $value.ContainsKey($script:NpmLockResolvedKey)) { continue }
        $resolved = [string] $value[$script:NpmLockResolvedKey]
        if (-not ($resolved.StartsWith($script:NpmFileProtocol) -and $resolved.EndsWith($script:NpmTarballExtension))) { continue }
        $full = Get-KitFullPath ($resolved.Substring($script:NpmFileProtocol.Length)) $InstallRootFull
        if (-not (Test-KitPathInside $full $SourceRoot)) { Stop-KitUsage "Lock file tarball '$resolved' is outside the source root." }
        $found += (Get-KitRelativePath $full $SourceRoot)
    }
    return @($found | Sort-Object -Unique)
}

# Lock-file package names in the install root that are Playwright packages (for PREREQUISITES.md).
function Get-KitPlaywrightVersions([string] $InstallRootFull) {
    $packages = Get-KitLockPackages $InstallRootFull
    $versions = @()
    foreach ($name in $script:PlaywrightPackages) {
        $key = $script:NpmNodeModulesPrefix + $name
        if ($packages.ContainsKey($key)) { $versions += "$name $($packages[$key][$script:NpmLockVersionKey])" }
    }
    return $versions
}

function Invoke-KitNpmCi([string] $Npm, [string] $InstallDir, [string] $CachePath, [bool] $Offline) {
    $arguments = @('ci', '--cache', $CachePath) + $script:NpmQuietArguments
    if ($Offline) { $arguments += '--offline' }
    return (Invoke-KitNative $Npm $arguments $InstallDir)
}

# Bins whose target is build output (dist/) get no shim at `npm ci` time; `npm rebuild --ignore-scripts` links them
# once the build has run, without running install scripts or touching the network.
function Get-KitNpmRelinkArguments([string] $CachePath) {
    return @($script:NpmRelinkArguments) + @('--cache', $CachePath) + $script:NpmQuietArguments
}

function Invoke-KitNpmRelinkBins([string] $Npm, [string] $InstallDir, [string] $CachePath) {
    return (Invoke-KitNative $Npm (Get-KitNpmRelinkArguments $CachePath) $InstallDir)
}

function Remove-KitNpmCacheNoise([string] $CachePath) {
    foreach ($name in $script:NpmCacheNoise) {
        $path = Join-Path $CachePath $name
        if (Test-Path -LiteralPath $path) { Remove-Item -LiteralPath $path -Recurse -Force }
    }
}

# The distinct install roots of the npm projects (one `npm ci` per root).
function Get-KitNpmInstallRoots([object[]] $NpmProjects) {
    return @($NpmProjects | ForEach-Object { $_.InstallRoot } | Sort-Object -Unique)
}

function Format-KitInstallRoot([string] $Relative) {
    if ($Relative) { return $Relative }
    return '.'
}

function New-KitOfflineText([object[]] $NpmProjects, [string[]] $FileTarballs) {
    $lines = @(
        '# Offline install', '',
        'Generated by deploy/handover/New-HandoverKit.ps1 (ADR-008). Paths are relative to the root of the delivered source tree.', '',
        '## NuGet', '',
        "Restore with the kit's ``$($script:KitNuGetConfigFile)`` only, for example:", '',
        '```powershell',
        "dotnet restore <project> --configfile <kit>\$($script:KitNuGetConfigFile)",
        '```', '',
        "Or copy ``$($script:KitNuGetConfigFile)`` over the source tree's root ``$($script:RepoNuGetConfigFile)`` after changing its folder source to the absolute path of ``<kit>\$($script:KitNuGetDir)``.", '',
        '## npm', '')
    if (@($NpmProjects).Count -eq 0) { return (($lines + @('No npm projects are in this kit.')) -join "`n") + "`n" }
    if (@($FileTarballs).Count -gt 0) {
        $lines += @("First copy every file under ``<kit>\$($script:KitNpmFilesDir)`` to the same relative path in the source tree:", '')
        $lines += @($FileTarballs | ForEach-Object { "- ``$_``" }) + @('')
    }
    $lines += @("In each install folder below, copy ``<kit>\$($script:KitNpmCacheDir)`` next to it (or point --cache at it) and run:", '',
        '```powershell', "npm ci --offline --cache ./$($script:KitNpmCacheDir)", '```', '')
    foreach ($root in Get-KitNpmInstallRoots $NpmProjects) {
        $members = @($NpmProjects | Where-Object { $_.InstallRoot -eq $root } | ForEach-Object { $_.Relative })
        $lines += "- ``$(Format-KitInstallRoot $root)`` (for $($members -join ', '))"
    }
    return ($lines -join "`n") + "`n"
}
