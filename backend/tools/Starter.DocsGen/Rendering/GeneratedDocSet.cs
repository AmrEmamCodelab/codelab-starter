using Starter.DocsGen.Collection;

namespace Starter.DocsGen.Rendering;

/// <summary>The file names DocsGen owns in the output folder.</summary>
internal static class GeneratedFileNames
{
    /// <summary>The normalized OpenAPI document (input of the frontend's api:gen).</summary>
    public const string OpenApi = "openapi.v1.json";

    /// <summary>The permission catalog, <c>{permissions:[{key, module, description}]}</c> (input of the frontend's api:gen).</summary>
    public const string PermissionsJson = "permissions.json";

    /// <summary>The permission catalog as a table.</summary>
    public const string PermissionsMarkdown = "permissions.md";

    /// <summary>Every endpoint with who may call it.</summary>
    public const string Endpoints = "endpoints.md";

    /// <summary>Every error code.</summary>
    public const string ErrorCodes = "error-codes.md";

    /// <summary>Every configuration key.</summary>
    public const string ConfigKeys = "config-keys.md";

    /// <summary>Every status enum with its values.</summary>
    public const string Statuses = "statuses.md";

    /// <summary>What the folder is and how to regenerate it.</summary>
    public const string Readme = "README.md";

    /// <summary>The subfolder of the workflow sheets (one per record type, plus its index).</summary>
    public const string WorkflowsFolder = "workflows";

    /// <summary>The index of the workflow sheets (always generated, also with zero workflows).</summary>
    public const string WorkflowIndex = WorkflowsFolder + FolderSeparator + Readme;

    /// <summary>The separator of a generated file's folder and name (the writer maps it to the platform's).</summary>
    public const string FolderSeparator = "/";

    private const string MarkdownExtension = ".md";

    /// <summary>The sheet of one workflow inside <see cref="WorkflowsFolder"/>: <c>service-request.md</c>.</summary>
    public static string WorkflowFileName(string recordType) => recordType + MarkdownExtension;

    /// <summary>The sheet of one workflow from the output folder: <c>workflows/service-request.md</c>.</summary>
    public static string Workflow(string recordType) => WorkflowsFolder + FolderSeparator + WorkflowFileName(recordType);
}

/// <summary>Renders every generated file from one <see cref="ApiSurface"/>; the same surface always gives the same bytes.</summary>
internal static class GeneratedDocSet
{
    /// <summary>The command that regenerates the folder.</summary>
    public const string RegenerateCommand = "dotnet run --project backend/tools/Starter.DocsGen -- --out docs/generated";

    /// <summary>The command that fails on drift.</summary>
    public const string CheckCommand = RegenerateCommand + " --check";

    /// <summary>The notice under every Markdown title.</summary>
    public const string MarkdownNotice =
        "> Generated by `backend/tools/Starter.DocsGen`. Do not edit; regenerate with `" + RegenerateCommand + "`.";

    /// <summary>File name (relative to the output folder, <c>/</c>-separated) to content, ordered by file name.</summary>
    public static IReadOnlyDictionary<string, string> Render(ApiSurface surface)
    {
        ArgumentNullException.ThrowIfNull(surface);
        var documents = new SortedDictionary<string, string>(StringComparer.Ordinal)
        {
            [GeneratedFileNames.OpenApi] = OpenApiNormalizer.Normalize(surface.OpenApiJson),
            [GeneratedFileNames.PermissionsJson] = PermissionsRenderer.RenderJson(surface.Permissions),
            [GeneratedFileNames.PermissionsMarkdown] = PermissionsRenderer.RenderMarkdown(surface.Permissions, surface.Endpoints),
            [GeneratedFileNames.Endpoints] = EndpointsRenderer.Render(surface.Endpoints),
            [GeneratedFileNames.ErrorCodes] = ErrorCodesRenderer.Render(surface.ErrorCodes),
            [GeneratedFileNames.ConfigKeys] = ConfigKeysRenderer.Render(surface.ConfigKeys),
            [GeneratedFileNames.Statuses] = StatusesRenderer.Render(surface.Statuses, surface.Workflows),
            [GeneratedFileNames.Readme] = ReadmeRenderer.Render(),
            [GeneratedFileNames.WorkflowIndex] = WorkflowIndexRenderer.Render(surface.Workflows),
        };
        foreach (var workflow in surface.Workflows)
        {
            documents[GeneratedFileNames.Workflow(workflow.RecordType)] = WorkflowRenderer.Render(workflow);
        }

        return documents;
    }
}
