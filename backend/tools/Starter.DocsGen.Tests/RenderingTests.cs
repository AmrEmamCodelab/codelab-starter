public sealed class MarkdownTextTests
{
    [Theory]
    [InlineData("a | b", "a \\| b")]
    [InlineData("line\r\nnext", "line next")]
    [InlineData("line\nnext", "line next")]
    [InlineData("  padded  ", "padded")]
    [InlineData(null, "")]
    public void Cells_are_escaped_and_single_line(string? value, string expected)
    {
        Assert.Equal(expected, MarkdownText.Cell(value));
    }

    [Fact]
    public void Code_wraps_and_keeps_empty_empty()
    {
        Assert.Equal("`x`", MarkdownText.Code("x"));
        Assert.Equal(string.Empty, MarkdownText.Code(string.Empty));
        Assert.Equal("`a'b`", MarkdownText.Code("a`b"));
    }

    [Fact]
    public void A_table_without_rows_is_the_note()
    {
        var text = new MarkdownText().Table(["A"], [], "Nothing.").ToString();

        Assert.Equal("Nothing.\n", text);
    }

    [Fact]
    public void Documents_end_with_exactly_one_newline()
    {
        var text = MarkdownText.Document("T").Line().Line().ToString();

        Assert.EndsWith("`.\n", text, StringComparison.Ordinal);
        Assert.StartsWith("# T\n\n> Generated by", text, StringComparison.Ordinal);
    }

    [Fact]
    public void Heading_level_must_be_positive()
    {
        Assert.Throws<ArgumentOutOfRangeException>(() => new MarkdownText().Heading(level: 0, "x"));
    }
}

public sealed class OpenApiNormalizerTests
{
    [Fact]
    public void Drops_servers_and_sorts_paths_and_components()
    {
        var normalized = OpenApiNormalizer.Normalize(SurfaceFixtures.OpenApi);
        var document = JsonNode.Parse(normalized)!.AsObject();

        Assert.False(document.ContainsKey(OpenApiNormalizer.ServersProperty));
        Assert.Equal(["/api/alpha", "/api/zeta"], document["paths"]!.AsObject().Select(entry => entry.Key));
        Assert.Equal(["Abc", "Zed"], document["components"]!["schemas"]!.AsObject().Select(entry => entry.Key));
    }

    [Fact]
    public void Output_is_lf_only_two_space_indented_and_idempotent()
    {
        var once = OpenApiNormalizer.Normalize(SurfaceFixtures.OpenApi);
        var twice = OpenApiNormalizer.Normalize(once);

        Assert.Equal(once, twice);
        Assert.DoesNotContain('\r', once);
        Assert.StartsWith("{\n  \"openapi\"", once, StringComparison.Ordinal);
        Assert.EndsWith("}\n", once, StringComparison.Ordinal);
    }

    [Fact]
    public void A_document_without_paths_or_components_is_kept()
    {
        Assert.Equal("{\n  \"openapi\": \"3.1.1\"\n}\n", OpenApiNormalizer.Normalize("{\"openapi\":\"3.1.1\"}"));
    }

    [Fact]
    public void A_non_object_is_refused()
    {
        Assert.Throws<InvalidOperationException>(() => OpenApiNormalizer.Normalize("[1]"));
    }
}

public sealed class PermissionsRendererTests
{
    [Fact]
    public void Json_has_the_contract_shape_sorted_by_key()
    {
        var json = PermissionsRenderer.RenderJson(SurfaceFixtures.Surface().Permissions);
        using var document = JsonDocument.Parse(json);
        var entries = document.RootElement.GetProperty("permissions").EnumerateArray().ToList();

        Assert.Single(document.RootElement.EnumerateObject());
        Assert.Equal(["other.edit", "sample.view"], entries.Select(entry => entry.GetProperty("key").GetString()));
        Assert.Equal(["key", "module", "description"], entries[0].EnumerateObject().Select(property => property.Name));
        Assert.Equal("Other", entries[0].GetProperty("module").GetString());
        Assert.EndsWith("}\n", json, StringComparison.Ordinal);
    }

    [Fact]
    public void Empty_catalog_is_an_empty_array()
    {
        Assert.Equal("{\n  \"permissions\": []\n}\n", PermissionsRenderer.RenderJson([]));
    }

    [Fact]
    public void Markdown_lists_each_key_with_the_endpoints_it_guards()
    {
        var surface = SurfaceFixtures.Surface();

        var markdown = PermissionsRenderer.RenderMarkdown(surface.Permissions, surface.Endpoints);

        Assert.Contains("| `sample.view` | Sample | Open the sample. | `GET /api/sample` |", markdown, StringComparison.Ordinal);
        Assert.Contains("| `other.edit` | Other | Edit \\| other. | none |", markdown, StringComparison.Ordinal);
        Assert.True(markdown.IndexOf("other.edit", StringComparison.Ordinal) < markdown.IndexOf("sample.view", StringComparison.Ordinal));
    }
}

public sealed class EndpointsRendererTests
{
    [Fact]
    public void Rows_are_sorted_by_route_then_method_with_access_text()
    {
        var markdown = EndpointsRenderer.Render(SurfaceFixtures.Surface().Endpoints);

        var login = markdown.IndexOf("/api/auth/login", StringComparison.Ordinal);
        var me = markdown.IndexOf("/api/me", StringComparison.Ordinal);
        var sample = markdown.IndexOf("/api/sample", StringComparison.Ordinal);
        Assert.True(login < me && me < sample);
        Assert.Contains("| POST | `/api/auth/login` | anonymous (allowlisted) | Identity | Signs in. |", markdown, StringComparison.Ordinal);
        Assert.Contains("| GET | `/api/me` | authenticated (allowlisted) | Access | Me. |", markdown, StringComparison.Ordinal);
        Assert.Contains("| GET | `/api/sample` | permission `sample.view` | Sample | Reads the sample. |", markdown, StringComparison.Ordinal);
    }

    [Fact]
    public void Several_permissions_are_all_listed()
    {
        var endpoint = new EndpointDoc("GET", "/x", EndpointAccessKind.Permission, ["a.b", "c.d"], "M", string.Empty);

        Assert.Equal("permission `a.b` + `c.d`", EndpointsRenderer.DescribeAccess(endpoint));
    }

    [Fact]
    public void An_unknown_access_kind_is_a_bug()
    {
        var endpoint = new EndpointDoc("GET", "/x", (EndpointAccessKind)99, [], "M", string.Empty);

        Assert.Throws<ArgumentOutOfRangeException>(() => EndpointsRenderer.DescribeAccess(endpoint));
    }

    [Fact]
    public void No_endpoints_is_a_note()
    {
        Assert.Contains("The host maps no endpoint.", EndpointsRenderer.Render([]), StringComparison.Ordinal);
    }
}

public sealed class ErrorCodesAndConfigRendererTests
{
    [Fact]
    public void Error_codes_are_grouped_by_owner_in_ordinal_order()
    {
        var markdown = ErrorCodesRenderer.Render(SurfaceFixtures.Surface().ErrorCodes);

        Assert.True(markdown.IndexOf("## Alpha", StringComparison.Ordinal) < markdown.IndexOf("## Sample", StringComparison.Ordinal));
        Assert.Contains("| `SAMPLE_GONE` | `SampleErrorCodes.Gone` | The sample is gone. |", markdown, StringComparison.Ordinal);
    }

    [Fact]
    public void Config_keys_are_grouped_by_owner_then_section()
    {
        var markdown = ConfigKeysRenderer.Render(SurfaceFixtures.Surface().ConfigKeys);

        Assert.True(markdown.IndexOf("## Kernel", StringComparison.Ordinal) < markdown.IndexOf("## Sample", StringComparison.Ordinal));
        Assert.Contains("### `Sample`", markdown, StringComparison.Ordinal);
        Assert.Contains("| `Sample:Limit` | int | `5` | The limit. |", markdown, StringComparison.Ordinal);
        Assert.Contains("| `Sample:Name` | string |  | The name. |", markdown, StringComparison.Ordinal);
    }

    [Fact]
    public void Empty_lists_render_a_note()
    {
        Assert.Contains("No error codes are declared.", ErrorCodesRenderer.Render([]), StringComparison.Ordinal);
        Assert.Contains("No options class declares a section.", ConfigKeysRenderer.Render([]), StringComparison.Ordinal);
    }
}

public sealed class GeneratedDocSetTests
{
    [Fact]
    public void Renders_every_contract_file()
    {
        var documents = GeneratedDocSet.Render(SurfaceFixtures.Surface());

        Assert.Equal(
            [
                GeneratedFileNames.Readme,
                GeneratedFileNames.ConfigKeys,
                GeneratedFileNames.Endpoints,
                GeneratedFileNames.ErrorCodes,
                GeneratedFileNames.OpenApi,
                GeneratedFileNames.PermissionsJson,
                GeneratedFileNames.PermissionsMarkdown,
                GeneratedFileNames.Statuses,
            ],
            documents.Keys);
    }

    [Fact]
    public void Same_surface_gives_the_same_bytes_lf_only_and_one_trailing_newline()
    {
        var first = GeneratedDocSet.Render(SurfaceFixtures.Surface());
        var second = GeneratedDocSet.Render(SurfaceFixtures.Surface());

        Assert.Equal(first, second);
        foreach (var (name, content) in first)
        {
            Assert.False(content.Contains('\r', StringComparison.Ordinal), name);
            Assert.EndsWith("\n", content, StringComparison.Ordinal);
            Assert.False(content.EndsWith("\n\n", StringComparison.Ordinal), name);
        }
    }

    [Fact]
    public void Input_order_does_not_change_the_output()
    {
        var surface = SurfaceFixtures.Surface();
        var reversed = surface with
        {
            Permissions = [.. surface.Permissions.Reverse()],
            Endpoints = [.. surface.Endpoints.Reverse()],
            ErrorCodes = [.. surface.ErrorCodes.Reverse()],
            ConfigKeys = [.. surface.ConfigKeys.Reverse()],
            Statuses = [.. surface.Statuses.Reverse().Select(status => status with { Members = [.. status.Members.Reverse()] })],
        };

        Assert.Equal(GeneratedDocSet.Render(surface), GeneratedDocSet.Render(reversed));
    }

    [Fact]
    public void Readme_names_both_commands_and_the_frontend_step()
    {
        var readme = ReadmeRenderer.Render();

        Assert.Contains(GeneratedDocSet.RegenerateCommand, readme, StringComparison.Ordinal);
        Assert.Contains(GeneratedDocSet.CheckCommand, readme, StringComparison.Ordinal);
        Assert.Contains("npm run api:gen", readme, StringComparison.Ordinal);
    }

    [Fact]
    public void Markdown_files_carry_the_generated_notice()
    {
        var documents = GeneratedDocSet.Render(SurfaceFixtures.Empty());

        foreach (var (name, content) in documents.Where(entry => entry.Key.EndsWith(".md", StringComparison.Ordinal)))
        {
            Assert.True(content.Contains(GeneratedDocSet.MarkdownNotice, StringComparison.Ordinal), name);
        }
    }
}
