// Builds the owned icon font (ADR-009) from icons/icons.json and the SVG sources in icons/svg, deterministically:
// the same inputs always give byte-identical outputs, so CI can regenerate and compare.
//
// Pipeline (all pinned root devDependencies): svgicons2svgfont (SVG icons -> SVG font, in manifest order) ->
// svg2ttf (TrueType, fixed timestamp) -> wawoff2 (WOFF2 compression). Outputs: the woff2, a JSON code point map and
// the TypeScript names and glyphs module that <dga-icon> imports.
import { Readable } from 'node:stream';
import { SVGIcons2SVGFontStream } from 'svgicons2svgfont';
import svg2ttf from 'svg2ttf';
import wawoff2 from 'wawoff2';
import { formatJson } from './files.mjs';

const ICON_NAME = /^[a-z][a-z0-9]*(?:-[a-z0-9]+)*$/;
const CODEPOINT = /^[0-9A-F]{4}$/;
const HEX_RADIX = 16;
/** The Unicode Private Use Area of the Basic Multilingual Plane: icon glyphs never collide with text. */
export const PRIVATE_USE_FIRST = 0xe000;
export const PRIVATE_USE_LAST = 0xf8ff;
/** Units per em of the generated font; the SVG sources are scaled to it (normalize). */
const FONT_HEIGHT = 1000;
const FONT_DESCENT = 0;
const FONT_VERSION = '1.0';
/** A fixed TrueType creation and modification time (the Unix epoch), so the font bytes never depend on the clock. */
const FIXED_TIMESTAMP = 0;
const FONT_ID = 'codelab-icons';
const FONT_DESCRIPTION = 'Codelab icon font for @codelab/ng-dga, generated from Bootstrap Icons (MIT).';
const FONT_VENDOR = '@codelab/ng-dga';

/** Every problem with the icon manifest; an empty list means it can be built. */
export function validateIconManifest(manifest, svgNames) {
  const errors = [];
  const names = new Set();
  const codepoints = new Set();
  for (const icon of manifest.icons ?? []) {
    if (!ICON_NAME.test(icon.name ?? '')) errors.push(`icon name '${icon.name}' must be kebab-case.`);
    if (names.has(icon.name)) errors.push(`icon '${icon.name}' is listed twice.`);
    names.add(icon.name);
    errors.push(...validateCodepoint(icon, codepoints));
    if (!svgNames.has(icon.name)) errors.push(`icon '${icon.name}' has no source icons/svg/${icon.name}.svg; run npm run assets:import.`);
  }
  for (const svgName of svgNames) {
    if (!names.has(svgName)) errors.push(`icons/svg/${svgName}.svg is not in icons.json.`);
  }
  if (names.size === 0) errors.push('icons.json lists no icons.');
  return errors;
}

function validateCodepoint(icon, seen) {
  if (!CODEPOINT.test(icon.codepoint ?? '')) return [`icon '${icon.name}' code point '${icon.codepoint}' must be four upper-case hex digits.`];
  const value = Number.parseInt(icon.codepoint, HEX_RADIX);
  const errors = [];
  if (value < PRIVATE_USE_FIRST || value > PRIVATE_USE_LAST) errors.push(`icon '${icon.name}' code point U+${icon.codepoint} is outside the Private Use Area.`);
  if (seen.has(value)) errors.push(`icon '${icon.name}' reuses code point U+${icon.codepoint}.`);
  seen.add(value);
  return errors;
}

function glyphOf(icon) {
  return String.fromCodePoint(Number.parseInt(icon.codepoint, HEX_RADIX));
}

async function svgFont(manifest, readSvg) {
  const stream = new SVGIcons2SVGFontStream({
    fontName: manifest.fontFamily,
    fontId: FONT_ID,
    fontHeight: FONT_HEIGHT,
    descent: FONT_DESCENT,
    normalize: true,
    centerHorizontally: true,
    fixedWidth: true,
    metadata: FONT_DESCRIPTION,
  });
  const chunks = [];
  const done = new Promise((resolve, reject) => {
    stream.on('data', (chunk) => chunks.push(Buffer.from(chunk)));
    stream.on('end', resolve);
    stream.on('error', reject);
  });
  for (const icon of manifest.icons) {
    const glyph = Readable.from([readSvg(icon.name)]);
    glyph.metadata = { name: icon.name, unicode: [glyphOf(icon)] };
    stream.write(glyph);
  }
  stream.end();
  await done;
  return Buffer.concat(chunks).toString('utf8');
}

/** The code point map shipped as assets/icons/<stem>.json (for apps, the showcase and documentation). */
export function renderCodepointMap(manifest) {
  const icons = Object.fromEntries(manifest.icons.map((icon) => [icon.name, { codepoint: icon.codepoint, mirrorInRtl: icon.mirrorInRtl === true }]));
  return formatJson({ fontFamily: manifest.fontFamily, icons });
}

function escapeGlyph(icon) {
  return `\\u{${icon.codepoint}}`;
}

/** The TypeScript module <dga-icon> imports: the name union, the glyph per name and the mirrored set. */
export function renderTypeScript(manifest) {
  const names = manifest.icons.map((icon) => `  | '${icon.name}'`).join('\n');
  const glyphs = manifest.icons.map((icon) => `  '${icon.name}': '${escapeGlyph(icon)}',`).join('\n');
  const mirrored = manifest.icons.filter((icon) => icon.mirrorInRtl === true).map((icon) => `'${icon.name}'`).join(', ');
  return [
    '// GENERATED by packages/npm/ng-dga/scripts/generate-icon-font.mjs from icons/icons.json. Do not edit;',
    '// change icons/icons.json and run `npm run icons:generate -w @codelab/ng-dga`.',
    '',
    '/** The name of an icon in the Codelab icon font. */',
    'export type DgaIconName =',
    `${names};`,
    '',
    '/** The Private Use Area character of each icon in the Codelab icon font. */',
    'export const DGA_ICON_GLYPHS: Readonly<Record<DgaIconName, string>> = {',
    glyphs,
    '};',
    '',
    '/** Icons drawn for left-to-right reading that mirror in right-to-left layouts (chevrons, arrows, logout). */',
    `export const DGA_ICONS_MIRRORED_IN_RTL: ReadonlySet<DgaIconName> = new Set<DgaIconName>([${mirrored}]);`,
    '',
  ].join('\n');
}

/**
 * Builds every output. `readSvg(name)` returns the SVG source text of an icon.
 * @returns {Promise<{ woff2: Buffer, codepointMap: string, typescript: string }>}
 */
export async function buildIconFont(manifest, readSvg) {
  const font = await svgFont(manifest, readSvg);
  const ttf = svg2ttf(font, {
    ts: FIXED_TIMESTAMP,
    version: FONT_VERSION,
    description: FONT_DESCRIPTION,
    url: FONT_VENDOR,
    copyright: FONT_DESCRIPTION,
  });
  const woff2 = Buffer.from(await wawoff2.compress(Buffer.from(ttf.buffer)));
  return { woff2, codepointMap: renderCodepointMap(manifest), typescript: renderTypeScript(manifest) };
}
