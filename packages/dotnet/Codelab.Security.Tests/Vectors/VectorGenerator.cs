using System.Text.Encodings.Web;
using System.Text.Json;
using System.Text.Json.Nodes;
using Codelab.Security.Signing;
using Codelab.Testing.Vectors;

namespace Codelab.Security.Tests.Vectors;

/// <summary>What every vector computation runs under: the protocol (prefix) and the fixture keys.</summary>
internal sealed record VectorContext(SecurityProtocol Protocol, FixtureKeySet Keys)
{
    /// <summary>The context for <paramref name="prefix"/> with the checked-in fixture keys.</summary>
    public static VectorContext For(string prefix) => new(SecurityProtocol.Create(prefix), FixtureKeySet.Default);

    /// <summary>The per-session signing key, derived exactly as the server derives it.</summary>
    public byte[] SessionKey(string masterKeyId, SessionIdentity session) =>
        new SessionKeyDerivation(Protocol).Derive(Keys.Signing.Bytes(masterKeyId), session);
}

/// <summary>
/// One vector file: its inputs (the case catalogue) and the computation that turns a case's inputs into its expected
/// values. The generator and the runner share <see cref="Compute"/>, so the checked-in expected values are, by
/// construction, what this implementation produces; the TypeScript runner is the independent half.
/// </summary>
internal interface IVectorArea
{
    /// <summary>The file stem (<c>canonical</c> for <c>canonical.vectors.json</c>).</summary>
    string Name { get; }

    /// <summary>The fixture key the file is pinned to.</summary>
    string FixtureKeyId(FixtureKeySet keys);

    /// <summary>The case inputs, in file order.</summary>
    IEnumerable<JsonObject> Inputs(VectorContext context);

    /// <summary>The expected values of one case, keyed by their <c>expected…</c> field name.</summary>
    IReadOnlyDictionary<string, string> Compute(GoldenVectorCase vectorCase, VectorContext context);
}

/// <summary>Builds and writes vector files.</summary>
internal static class VectorGenerator
{
    /// <summary>The vector file suffix.</summary>
    public const string FileSuffix = ".vectors.json";

    /// <summary>The format version of every file.</summary>
    public const int SchemaVersion = 1;

    /// <summary>The fixture-key id of a file that uses no key.</summary>
    public const string NoFixtureKey = "none";

    private const string SchemaVersionField = "schemaVersion";
    private const string AreaField = "area";
    private const string PrefixField = "prefix";
    private const string FixtureKeyIdField = "fixtureKeyId";
    private const string NoticeField = "notice";
    private const string CasesField = "cases";
    private const string Notice = "TEST-ONLY golden vectors over the starter fixture keys (packages/vectors/fixture-keys). Generated by Codelab.Security.Tests/Vectors (CODELAB_REGEN_VECTORS=1); never edit by hand.";
    private const char NewLine = '\n';

    private static readonly JsonSerializerOptions Output = new()
    {
        WriteIndented = true,
        NewLine = "\n",
        Encoder = JavaScriptEncoder.UnsafeRelaxedJsonEscaping,
    };

    /// <summary>Every vector area, in a fixed order.</summary>
    public static IReadOnlyList<IVectorArea> Areas { get; } =
    [
        new CanonicalVectors(),
        new SessionKeyVectors(),
        new RequestSignatureVectors(),
        new ResponseSignatureVectors(),
        new PublicIdVectors(),
    ];

    /// <summary>The file text of <paramref name="area"/> under <paramref name="context"/>.</summary>
    public static string Generate(IVectorArea area, VectorContext context)
    {
        var cases = new JsonArray();
        foreach (var input in area.Inputs(context))
        {
            foreach (var (field, value) in area.Compute(ParseCase(input, context), context))
            {
                input[field] = value;
            }

            cases.Add(input);
        }

        var root = Header(area, context);
        root[CasesField] = cases;
        return root.ToJsonString(Output) + NewLine;
    }

    /// <summary>Writes every area into <paramref name="directory"/>; returns the written paths.</summary>
    public static IReadOnlyList<string> WriteAll(string directory, VectorContext context)
    {
        Directory.CreateDirectory(directory);
        var written = new List<string>();
        foreach (var area in Areas)
        {
            var path = VectorEnvironment.FileIn(directory, area);
            File.WriteAllText(path, Generate(area, context));
            written.Add(path);
        }

        return written;
    }

    private static JsonObject Header(IVectorArea area, VectorContext context) => new()
    {
        [SchemaVersionField] = SchemaVersion,
        [AreaField] = area.Name,
        [PrefixField] = context.Protocol.Prefix,
        [FixtureKeyIdField] = area.FixtureKeyId(context.Keys),
        [NoticeField] = Notice,
    };

    // The generator reads its own inputs through the same parser the runner uses, so both see identical values.
    private static GoldenVectorCase ParseCase(JsonObject input, VectorContext context)
    {
        var wrapper = new JsonObject
        {
            [SchemaVersionField] = SchemaVersion,
            [PrefixField] = context.Protocol.Prefix,
            [FixtureKeyIdField] = NoFixtureKey,
            [CasesField] = new JsonArray(input.DeepClone()),
        };
        return GoldenVectorFile.Parse(wrapper.ToJsonString(), nameof(VectorGenerator)).Cases[0];
    }
}
