using System.Security.Cryptography;

namespace Codelab.Security.ServiceAuth;

/// <summary>
/// The calling side of the service-to-service scheme (<c>Codelab:Security:ServiceAssertions:Client</c>): this
/// service's name, the audience it calls, and its ES256 (P-256) private key as PKCS#8 PEM.
/// </summary>
public sealed class ServiceAssertionClientOptions
{
    /// <summary>The configuration section.</summary>
    public const string SectionName = SecuritySections.ServiceAssertionClient;

    /// <summary>This service's name (the <c>iss</c> claim); the server looks its key up by <see cref="KeyId"/>.</summary>
    public string? ServiceName { get; set; }

    /// <summary>The audience of the called service (its configured <c>Audience</c>).</summary>
    public string? Audience { get; set; }

    /// <summary>The key id (the <c>kid</c> header).</summary>
    public string? KeyId { get; set; }

    /// <summary>The ES256 private key, PKCS#8 PEM (from the environment or a secret store, generated by init.ps1).</summary>
    public string? PrivateKeyPem { get; set; }

    /// <summary>Assertion lifetime in seconds (short: each assertion covers one request).</summary>
    public int LifetimeSeconds { get; set; } = 30;
}

/// <summary>
/// The receiving side (<c>Codelab:Security:ServiceAssertions:Server</c>): this service's audience, the accepted
/// assertion age and the public keys of the services allowed to call it.
/// </summary>
public sealed class ServiceAssertionServerOptions
{
    /// <summary>The configuration section.</summary>
    public const string SectionName = SecuritySections.ServiceAssertionServer;

    /// <summary>This service's audience (callers must put exactly this in <c>aud</c>).</summary>
    public string? Audience { get; set; }

    /// <summary>The longest accepted lifetime (exp - iat) in seconds.</summary>
    public int MaxLifetimeSeconds { get; set; } = 60;

    /// <summary>Clock skew tolerated on iat and exp, in seconds.</summary>
    public int ClockSkewSeconds { get; set; } = 5;

    /// <summary>The largest request body hashed for the body binding; a bigger body fails authentication.</summary>
    public int MaxBodyBytes { get; set; } = 10 * 1024 * 1024;

    /// <summary>The services allowed to call, each with its public key.</summary>
    public IList<TrustedServiceOptions> TrustedServices { get; init; } = [];
}

/// <summary>A calling service and its ES256 public key (SubjectPublicKeyInfo PEM).</summary>
public sealed class TrustedServiceOptions
{
    /// <summary>The service name it must assert as <c>iss</c>.</summary>
    public string? ServiceName { get; set; }

    /// <summary>The key id it signs with.</summary>
    public string? KeyId { get; set; }

    /// <summary>The ES256 public key, PEM.</summary>
    public string? PublicKeyPem { get; set; }
}

/// <summary>Loads and checks P-256 keys from PEM.</summary>
internal static class ServiceKeys
{
    internal static ECDsa ImportP256(string pem)
    {
        var key = ECDsa.Create();
        try
        {
            key.ImportFromPem(pem);
            if (key.KeySize != ServiceAssertionToken.KeySizeBits)
            {
                throw new CryptographicException("The key is not a P-256 key.");
            }

            return key;
        }
        catch
        {
            key.Dispose();
            throw;
        }
    }

    internal static string? Problem(string? pem, string settingPath)
    {
        if (string.IsNullOrWhiteSpace(pem))
        {
            return $"{settingPath} is required.";
        }

        try
        {
            using var key = ImportP256(pem);
            return null;
        }
        catch (Exception ex) when (ex is CryptographicException or ArgumentException)
        {
            return $"{settingPath} is not a P-256 (ES256) key in PEM form.";
        }
    }
}
