using System.Globalization;
using Codelab.Build.Analyzers.Analyzers;
using Codelab.Build.Analyzers.Options;
using Codelab.Build.Analyzers.Tests.Harness;

namespace Codelab.Build.Analyzers.Tests;

public sealed class FileLengthAnalyzerTests
{
    private static AnalyzerTest Test() => new(new FileLengthAnalyzer());

    [Fact]
    public async Task A_file_at_the_default_limit_passes_and_one_line_more_is_CLB1002_on_the_first_line()
    {
        var atLimit = await Test().RunAsync(SourceText.FileWithCodeLines(DefaultThresholds.FileLines));
        var overLimit = await Test().RunAsync(SourceText.FileWithCodeLines(DefaultThresholds.FileLines + 1));

        Assert.Empty(atLimit);
        var diagnostic = Assert.Single(overLimit);
        Assert.Equal(DiagnosticIds.FileTooLong, diagnostic.Id);
        Assert.Equal(0, diagnostic.Location.GetLineSpan().StartLinePosition.Line);
        Assert.StartsWith("'Sample.cs' has 401 lines of code; the limit is 400 ", diagnostic.GetMessage(CultureInfo.InvariantCulture), StringComparison.Ordinal);
    }

    [Fact]
    public async Task The_limit_comes_from_codelab_file_lines()
    {
        var atLimit = await Test().WithOption(OptionKeys.FileLines, "10").RunAsync(SourceText.FileWithCodeLines(codeLines: 10));
        var overLimit = await Test().WithOption(OptionKeys.FileLines, "10").RunAsync(SourceText.FileWithCodeLines(codeLines: 11));

        Assert.Empty(atLimit);
        Assert.Single(overLimit);
    }

    [Fact]
    public async Task Generated_files_are_not_measured()
    {
        var source = "// <auto-generated/>\n" + SourceText.FileWithCodeLines(codeLines: 11);

        var diagnostics = await Test().WithOption(OptionKeys.FileLines, "10").RunAsync(source);

        Assert.Empty(diagnostics);
    }
}
